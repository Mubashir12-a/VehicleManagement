const todayDateStr = new Date().toISOString().split('T')[0]

function calcFutureDate(years) {
  const d = new Date()
  d.setFullYear(d.getFullYear() + years)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

